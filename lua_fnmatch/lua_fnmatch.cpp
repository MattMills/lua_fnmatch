struct image_box
{
    fnme_image *image;
    uint64_t base; // addresses are base + rva
};

struct sigfile_box
{
    fnme_sigfile *sigfile;
};

constexpr const char *image_tname = "fnmatch.image";
constexpr const char *sigfile_tname = "fnmatch.sig_file";

image_box *check_image(lua_State *L, int idx)
{
    auto *box = static_cast<image_box *>(compat::testudata(L, idx, image_tname));
    if (box == nullptr) {
        type_error(L, idx, image_tname);
    }
    if (box->image == nullptr) {
        luaL_argerror(L, idx, "the image is closed");
    }
    return box;
}

sigfile_box *check_sigfile(lua_State *L, int idx)
{
    auto *box = static_cast<sigfile_box *>(compat::testudata(L, idx, sigfile_tname));
    if (box == nullptr) {
        type_error(L, idx, sigfile_tname);
    }
    if (box->sigfile == nullptr) {
        luaL_argerror(L, idx, "the sig file is closed");
    }
    return box;
}

