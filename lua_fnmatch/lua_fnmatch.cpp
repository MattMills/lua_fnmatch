// fnmatch.sig_file(path) -> sig file | nil, message: a .sig file of stellar-fnmatch
int sigfile_open(lua_State *L)
{
    const char *path = check_text(L, 1, "path");
    auto *box = static_cast<sigfile_box *>(compat::newuserdata(L, sizeof(sigfile_box)));
    box->sigfile = nullptr;
    luaL_getmetatable(L, sigfile_tname);
    lua_setmetatable(L, -2);
    char err[error_size] = "";
    box->sigfile = fnme_sigfile_open(path, err, sizeof(err));
    if (box->sigfile == nullptr) {
        return fail(L, err);
    }
    return 1;
}

void push_sigfile_function(lua_State *L, const sigfile_box *box, uint32_t index)
{
    fnme_function f;
    if (!fnme_sigfile_function(box->sigfile, index, &f)) {
        lua_pushnil(L);
        return;
    }
    lua_createtable(L, 0, 8);
    push_unsigned(L, static_cast<uint64_t>(index) + 1);
    lua_setfield(L, -2, "index");
    push_unsigned(L, f.rva);
    lua_setfield(L, -2, "rva");
    push_unsigned(L, f.end_rva);
    lua_setfield(L, -2, "end_rva");
    push_unsigned(L, f.size);
    lua_setfield(L, -2, "size");
    push_unsigned(L, f.instructions);
    lua_setfield(L, -2, "instructions");
    fnme_function owner;
    if (f.funclet_of != UINT32_MAX && fnme_sigfile_function(box->sigfile, f.funclet_of, &owner)) {
        push_unsigned(L, owner.rva);
        lua_setfield(L, -2, "funclet_of");
        push_kind_of_funclet(L, f.funclet_kind);
        lua_setfield(L, -2, "funclet_kind");
    }
    lua_createtable(L, static_cast<int>(f.names), 0);
    for (uint32_t k = 0; k < f.names; ++k) {
        push_engine_text(L, [&](char *buf, size_t size) {
            return fnme_sigfile_function_name(box->sigfile, index, k, buf, size);
        });
        lua_rawseti(L, -2, static_cast<int>(k + 1));
    }
    lua_setfield(L, -2, "names");
}

