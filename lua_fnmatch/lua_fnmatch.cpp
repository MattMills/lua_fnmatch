// Pushes an empty image userdata; the caller fills it in.
image_box *push_image(lua_State *L)
{
    auto *box = static_cast<image_box *>(compat::newuserdata(L, sizeof(image_box)));
    box->image = nullptr;
    box->base = 0;
    luaL_getmetatable(L, image_tname);
    lua_setmetatable(L, -2);
    return box;
}

// Analyses the file at `path` into a new image userdata (pushed), or returns nil, message.
int open_image(lua_State *L, const char *path, const image_options &o, bool loaded, uint64_t load_base)
{
    image_box *box = push_image(L);
    char err[error_size] = "";
    box->image = fnme_image_open(path, &o.engine, err, sizeof(err));
    if (box->image == nullptr) {
        return fail(L, err);
    }
    box->base = loaded ? load_base : (o.has_base ? o.base : fnme_image_preferred_base(box->image));
    return 1;
}

// fnmatch.file(path [, options]) -> image | nil, message
//   options: pdb, base (default: the PE image base), cache, threads
int image_file(lua_State *L)
{
    static const char *const allowed[] = {"pdb", "base", "cache", "threads", nullptr};
    const char *path = check_text(L, 1, "path");
    const image_options o = check_options(L, 2, allowed);
    return open_image(L, path, o, false, 0);
}

// fnmatch.image(contents [, options]) -> image | nil, message: the executable as a string
//   options: pdb, base, cache, threads, name (for messages)
int image_from_string(lua_State *L)
{
    static const char *const allowed[] = {"pdb", "base", "cache", "threads", "name", nullptr};
    size_t size = 0;
    const char *data = luaL_checklstring(L, 1, &size);
    const image_options o = check_options(L, 2, allowed);
    image_box *box = push_image(L);
    char err[error_size] = "";
    box->image = fnme_image_from_memory(
        reinterpret_cast<const uint8_t *>(data), size, o.name != nullptr ? o.name : "(string)", &o.engine, err,
        sizeof(err));
    if (box->image == nullptr) {
        return fail(L, err);
    }
    box->base = o.has_base ? o.base : fnme_image_preferred_base(box->image);
    return 1;
}

// fnmatch.module(name [, options]) -> image | nil, message: a module loaded in this process,
// analysed from its file, with addresses where it is loaded
//   options: pdb, cache, threads
int image_module(lua_State *L)
{
    static const char *const allowed[] = {"pdb", "cache", "threads", nullptr};
    const char *name = check_text(L, 1, "module name");
    const image_options o = check_options(L, 2, allowed);

#if defined(_WIN32)
    wchar_t wide_name[1024];
    if (MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, name, -1, wide_name, 1024) == 0) {
        luaL_argerror(L, 1, "invalid module name");
    }
    const HMODULE module = GetModuleHandleW(wide_name);
    if (module == nullptr) {
        lua_pushfstring(L, "module not loaded: %s", name);
        return fail(L, lua_tostring(L, -1));
    }
    constexpr DWORD wide_size = 32768;
    auto *wide_path = static_cast<wchar_t *>(push_buffer(L, wide_size * sizeof(wchar_t)));
    const DWORD n = GetModuleFileNameW(module, wide_path, wide_size);
    if (n == 0 || n >= wide_size) {
        lua_pushfstring(L, "no file name for module %s", name);
        return fail(L, lua_tostring(L, -1));
    }
    const int size = WideCharToMultiByte(CP_UTF8, 0, wide_path, -1, nullptr, 0, nullptr, nullptr);
    auto *path = static_cast<char *>(push_buffer(L, size > 0 ? static_cast<size_t>(size) : 1));
    if (size <= 0 || WideCharToMultiByte(CP_UTF8, 0, wide_path, -1, path, size, nullptr, nullptr) == 0) {
        lua_pushfstring(L, "no file name for module %s", name);
        return fail(L, lua_tostring(L, -1));
    }
    return open_image(L, path, o, true, reinterpret_cast<uintptr_t>(module));
#else
    // A module is a file mapped in /proc/self/maps; its base is the mapping of file offset 0.
    FILE *maps = std::fopen("/proc/self/maps", "r");
    if (maps == nullptr) {
        return fail(L, "cannot read /proc/self/maps");
    }
    auto *line = static_cast<char *>(push_buffer(L, 8192));
    auto *path = static_cast<char *>(push_buffer(L, 4096));
    path[0] = '\0';
    uint64_t base = 0;
    while (std::fgets(line, 8192, maps) != nullptr) {
        unsigned long long start = 0, end = 0, offset = 0, inode = 0;
        char perms[8], dev[32];
        int pos = 0;
        if (std::sscanf(line, "%llx-%llx %7s %llx %31s %llu %n", &start, &end, perms, &offset, dev, &inode, &pos) < 6 || pos == 0) {
            continue;
        }
        char *file = line + pos;
        file[std::strcspn(file, "\n")] = '\0';
        const char *slash = std::strrchr(file, '/');
        if (file[0] != '/' || slash == nullptr || strcasecmp(slash + 1, name) != 0 || offset != 0) {
            continue;
        }
        if (path[0] == '\0' || start < base) {
            base = start;
            std::snprintf(path, 4096, "%s", file);
        }
    }
    std::fclose(maps);
    if (path[0] == '\0') {
        lua_pushfstring(L, "module not loaded: %s", name);
        return fail(L, lua_tostring(L, -1));
    }
    return open_image(L, path, o, true, base);
#endif
}

void push_kind_of_funclet(lua_State *L, uint8_t kind)
{
    if (kind == 1) {
        lua_pushliteral(L, "unwind");
    }
    else if (kind == 2) {
        lua_pushliteral(L, "catch");
    }
    else {
        lua_pushnil(L);
    }
}

// Pushes the description of function `index` of an image, or nil.
void push_image_function(lua_State *L, const image_box *box, uint32_t index)
{
    fnme_function f;
    if (!fnme_image_function(box->image, index, &f)) {
        lua_pushnil(L);
        return;
    }
    lua_createtable(L, 0, 10);
    push_unsigned(L, static_cast<uint64_t>(index) + 1);
    lua_setfield(L, -2, "index");
    push_unsigned(L, box->base + f.rva);
    lua_setfield(L, -2, "address");
    push_unsigned(L, box->base + f.end_rva);
    lua_setfield(L, -2, "end_address");
    push_unsigned(L, f.rva);
    lua_setfield(L, -2, "rva");
    push_unsigned(L, f.size);
    lua_setfield(L, -2, "size");
    push_unsigned(L, f.instructions);
    lua_setfield(L, -2, "instructions");
    push_unsigned(L, f.flags);
    lua_setfield(L, -2, "flags");
    fnme_function owner;
    if (f.funclet_of != UINT32_MAX && fnme_image_function(box->image, f.funclet_of, &owner)) {
        push_unsigned(L, box->base + owner.rva);
        lua_setfield(L, -2, "funclet_of");
        push_kind_of_funclet(L, f.funclet_kind);
        lua_setfield(L, -2, "funclet_kind");
    }
    lua_createtable(L, static_cast<int>(f.names), 0);
    for (uint32_t k = 0; k < f.names; ++k) {
        push_engine_text(L, [&](char *buf, size_t size) {
            return fnme_image_function_name(box->image, index, k, buf, size);
        });
        lua_rawseti(L, -2, static_cast<int>(k + 1));
    }
    lua_setfield(L, -2, "names");
}

// The function of an image containing the address at `idx`, or -1.
int64_t image_function_index(lua_State *L, const image_box *box, int idx)
{
    const uint64_t address = check_address(L, idx);
    if (address < box->base || address - box->base > UINT32_MAX) {
        return -1;
    }
    return fnme_image_function_containing(box->image, static_cast<uint32_t>(address - box->base));
}

