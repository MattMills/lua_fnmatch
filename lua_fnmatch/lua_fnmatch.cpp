constexpr size_t error_size = 1024;

[[noreturn]] void type_error(lua_State *L, int idx, const char *expected)
{
    luaL_argerror(L, idx, lua_pushfstring(L, "%s expected, got %s", expected, luaL_typename(L, idx)));
    std::abort(); // unreachable, luaL_argerror does not return
}

// Returns nil and a message: the Lua convention for failures that are not programming errors.
int fail(lua_State *L, const char *message)
{
    lua_pushnil(L);
    lua_pushstring(L, message);
    return 2;
}

void push_unsigned(lua_State *L, uint64_t value)
{
#if LUA_VERSION_NUM >= 503
    lua_pushinteger(L, static_cast<lua_Integer>(value));
#else
    lua_pushnumber(L, static_cast<lua_Number>(value));
#endif
}

// A non-negative integral number, or nothing.
std::optional<uint64_t> to_unsigned(lua_State *L, int idx)
{
    if (lua_type(L, idx) != LUA_TNUMBER) {
        return std::nullopt;
    }
#if LUA_VERSION_NUM >= 503
    if (lua_isinteger(L, idx)) {
        const lua_Integer value = lua_tointeger(L, idx);
        if (value < 0) {
            return std::nullopt;
        }
        return static_cast<uint64_t>(value);
    }
#endif
    const lua_Number value = lua_tonumber(L, idx);
    if (!(value >= 0) || value >= 18446744073709551616.0 || std::floor(value) != value) {
        return std::nullopt;
    }
    return static_cast<uint64_t>(value);
}

uint64_t check_unsigned(lua_State *L, int idx, uint64_t max, const char *what)
{
    const auto value = to_unsigned(L, idx);
    if (!value.has_value() || value.value() > max) {
        if (lua_type(L, idx) != LUA_TNUMBER) {
            type_error(L, idx, what);
        }
        luaL_argerror(L, idx, lua_pushfstring(L, "%s out of range", what));
    }
    return value.value();
}

// An address is an integer (as returned by this module) or a light userdata.
uint64_t check_address(lua_State *L, int idx)
{
    if (lua_islightuserdata(L, idx)) {
        return reinterpret_cast<uintptr_t>(lua_touserdata(L, idx));
    }
#if LUA_VERSION_NUM >= 503
    if (lua_isinteger(L, idx)) {
        return static_cast<uint64_t>(lua_tointeger(L, idx)); // wraps like push_unsigned()
    }
#endif
    return check_unsigned(L, idx, std::numeric_limits<uint64_t>::max(), "address");
}

// A string argument without zero bytes (the engine takes C strings).
const char *check_text(lua_State *L, int idx, const char *what)
{
    if (lua_type(L, idx) != LUA_TSTRING) {
        type_error(L, idx, what);
    }
    size_t length = 0;
    const char *text = lua_tolstring(L, idx, &length);
    if (std::strlen(text) != length) {
        luaL_argerror(L, idx, lua_pushfstring(L, "%s contains a zero byte", what));
    }
    return text;
}

// Scratch memory owned by Lua: a userdata pushed on the stack, collected also after an error.
void *push_buffer(lua_State *L, size_t size)
{
    return compat::newuserdata(L, size == 0 ? 1 : size);
}

// Pushes a string that the engine copies out snprintf-style: `get(buf, size)` returns its length.
template <class GetT>
void push_engine_text(lua_State *L, GetT &&get)
{
    char small[256];
    const size_t length = get(small, sizeof(small));
    if (length < sizeof(small)) {
        lua_pushlstring(L, small, length);
        return;
    }
    char *big = static_cast<char *>(push_buffer(L, length + 1));
    get(big, length + 1);
    lua_pushlstring(L, big, length);
    lua_remove(L, -2);
}

// Fetches a list that the engine copies out: `get(out, max)` returns its full length. The list
// lives in a buffer pushed on the stack.
template <class T, class GetT>
T *push_engine_list(lua_State *L, GetT &&get, size_t *count)
{
    const size_t total = get(nullptr, 0);
    T *list = static_cast<T *>(push_buffer(L, total * sizeof(T)));
    const size_t again = get(list, total);
    *count = again < total ? again : total;
    return list;
}

