// Creates the metatable of a userdata type. `index` is the __index function and receives the
// methods table as upvalue 1.
void register_type(
    lua_State *L, const char *tname, const luaL_Reg *methods, const luaL_Reg *metamethods, lua_CFunction index,
    lua_CFunction gc)
{
    luaL_newmetatable(L, tname);
    lua_pushcfunction(L, gc);
    lua_setfield(L, -2, "__gc");
    lua_pushstring(L, tname);
    lua_setfield(L, -2, "__metatable"); // protects __gc from being called again
    compat::setfuncs(L, metamethods);
    lua_newtable(L);
    compat::setfuncs(L, methods);
    lua_pushcclosure(L, index, 1);
    lua_setfield(L, -2, "__index");
    lua_pop(L, 1);
}

