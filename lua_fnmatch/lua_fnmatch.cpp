struct image_options
{
    fnme_options engine{}; // pdb, cache_dir, threads
    const char *name = nullptr;
    uint64_t base = 0;
    bool has_base = false;
};

// Reads the options table at `idx`, allowing the option names in `allowed`. The option strings are
// left on the stack, which keeps them valid.
image_options check_options(lua_State *L, int idx, const char *const *allowed)
{
    image_options o;
    if (lua_isnoneornil(L, idx)) {
        return o;
    }
    idx = compat::absindex(L, idx);
    if (!lua_istable(L, idx)) {
        type_error(L, idx, "options table");
    }
    lua_pushnil(L);
    while (lua_next(L, idx) != 0) {
        lua_pop(L, 1);
        if (lua_type(L, -1) != LUA_TSTRING) {
            luaL_argerror(L, idx, "option names are strings");
        }
        bool known = false;
        for (const char *const *a = allowed; *a != nullptr; ++a) {
            known = known || std::strcmp(lua_tostring(L, -1), *a) == 0;
        }
        if (!known) {
            luaL_argerror(L, idx, lua_pushfstring(L, "unknown option '%s'", lua_tostring(L, -1)));
        }
    }

    lua_getfield(L, idx, "pdb");
    if (!lua_isnil(L, -1)) {
        o.engine.pdb = check_text(L, -1, "pdb path");
    }
    lua_getfield(L, idx, "cache");
    if (!lua_isnil(L, -1)) {
        o.engine.cache_dir = check_text(L, -1, "cache directory");
    }
    lua_getfield(L, idx, "name");
    if (!lua_isnil(L, -1)) {
        o.name = check_text(L, -1, "name");
    }
    lua_getfield(L, idx, "threads");
    if (!lua_isnil(L, -1)) {
        o.engine.threads = static_cast<uint32_t>(check_unsigned(L, lua_gettop(L), 4096, "threads"));
    }
    lua_getfield(L, idx, "base");
    if (!lua_isnil(L, -1)) {
        o.base = check_address(L, lua_gettop(L));
        o.has_base = true;
    }
    return o;
}

