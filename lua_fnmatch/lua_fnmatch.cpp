// lua_fnmatch.cpp : Lua bindings for stellar-fnmatch function signatures.
//
// The work is done by the engine (Rust, engine/include/fnmatch_engine.h): an image is an
// executable analysed into its functions and every signature of every function. This file
// exposes images, .sig files and signatures to Lua; see README.md for the Lua API.
//
// Two rules keep the binding safe in a host process (as in lua_sigmatch):
//
// - Lua errors are only raised while no C++ object that owns resources is alive. With PUC Lua
//   built as C, errors are longjmp()s that skip destructors. Engine objects are stored in their
//   userdata as soon as they exist, scratch memory is Lua userdata, and no C++ containers are
//   used.
// - The engine never unwinds into this code: it reports errors and panics as messages.

#include "lua_fnmatch.h"

#include "fnmatch_engine.h"
